// Record the network fixture for the deterministic PUBLIC no-op capture.
//
// Runs the public flow ONCE against the live backend and saves every same-origin data response, so
// every later gate run replays those exact bytes offline. This is the only script in the harness
// that touches the network, and it is never run by ab.sh — re-run it by hand when the fixture needs
// refreshing (a new pair, a new endpoint, a changed response shape).
//
// env INPUTS = input-set json (default ../../STAGE_11F_PUBLIC_NOOP_INPUTS.json)
// env OUT    = override the fixture path (default: the spec's flow.stubFile)
const path = require('path');
const fs = require('fs');
const APP_ROOT = path.resolve(__dirname, '..', '..');
const puppeteer = require(path.join(APP_ROOT, 'node_modules', 'puppeteer-core'));
const CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const { attachRecorder } = require('./stub');
const { driveFlow } = require('./flow');

const INPUTS = process.env.INPUTS || path.join(APP_ROOT, 'STAGE_11F_PUBLIC_NOOP_INPUTS.json');
const BASE = process.env.BASE_URL || 'http://localhost:3001';
const spec = JSON.parse(fs.readFileSync(INPUTS, 'utf8'));
const OUT = process.env.OUT || path.join(APP_ROOT, spec.flow.stubFile);

(async () => {
  const b = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox'] });
  const page = await b.newPage();
  await page.setViewport({ width: 1440, height: 1000 });
  const cErr = [], pErr = [];
  page.on('console', m => { if (m.type() === 'error') cErr.push(m.text()); });
  page.on('pageerror', e => pErr.push(e.message));

  const store = {};
  attachRecorder(page, store);

  await page.goto(BASE, { waitUntil: 'domcontentloaded', timeout: 60000 });
  const { missingInputs } = await driveFlow(page, spec);

  const ids = await page.evaluate(() =>
    [...document.querySelectorAll('[data-section-id]')].map(e => e.getAttribute('data-section-id')));

  const keys = Object.keys(store).sort();
  const bytes = keys.reduce((n, k) => n + store[k].body.length, 0);
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, JSON.stringify({
    _description: 'RECORDED network fixture for the public no-op capture. Generated by tools/noop-ab/record.js — do not hand-edit.',
    recordedAt: new Date().toISOString(),
    inputs: path.basename(INPUTS),
    responses: store,
  }, null, 1));

  console.log(`recorded ${keys.length} responses (${(bytes / 1024).toFixed(0)} KB of bodies) -> ${OUT}`);
  console.log(`sections=${ids.length} missing=[${missingInputs.join(',')}] cErr=${cErr.length} pErr=${pErr.length}`);
  console.log('keys:'); keys.forEach(k => console.log(`  ${k}  (${store[k].status}, ${store[k].body.length}B)`));
  // A key carrying today's date would miss on a later run — surface it rather than let the gate
  // fail mysteriously tomorrow.
  const dated = keys.filter(k => /\d{4}-\d{2}-\d{2}|\d{10,13}/.test(k));
  if (dated.length) console.log('WARNING date/timestamp-bearing keys (will miss on a later run):', dated);
  if (missingInputs.length) console.error('WARNING inputs the DOM never exposed:', missingInputs);
  if (spec.flow.expectedSections && ids.length !== spec.flow.expectedSections)
    console.error(`WARNING captured ${ids.length} sections, expected ${spec.flow.expectedSections}`);
  await b.close();
})().catch(e => { console.error('FATAL', e.message); process.exit(1); });
